#string indexing

credit_number = "1234-5678-9012-3456"

print(credit_number[0])         #0-based indexing
print(credit_number[:4])        #start substring
print(credit_number[5:9])       #mid substring
print(credit_number[5:])        #end substring
print(credit_number[-1])        #from ending
print(credit_number[::2])       #step
print(credit_number[::-3])      #ending
print(credit_number[::-1])      #reverse